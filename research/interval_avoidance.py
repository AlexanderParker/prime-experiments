"""Interval avoidance: the one knob that separates primes from twin primes.

In the halved coordinates of research/halved_coordinates.py the algorithm is:

    least h >= 1 such that h mod q is not in a blocked interval, for every odd
    prime q <= y

with a blocked interval of length L = 1 for the next-prime search and L = 2 for
the twin search (the two blocked residues turn out to be adjacent). Everything
else about the two searches is identical.

Realisable states are diagonal: for base n the blocked residue is
d_q = -n * inverse(2) mod q, which is the reduction of the single integer
-n * inverse(2) mod P where P is the odd primorial. So the worst case over all
bases n is exactly the largest gap in the canonical pattern

    S(L, y) = { h : h mod q not in [0, L) for every odd prime q <= y }

Define F(L, y) = that largest gap. Then:

  * F(1, y) is the cost of finding the next prime.
  * F(2, y) is the cost of finding the next twin pair.
  * A twin pair exists below y^2 as soon as 2 * F(2, y) < y^2 - y - 2, because
    the algorithm's divisor set stays complete over that whole window. So the
    twin prime conjecture follows from any proof that F(2, y) grows slower than
    y^2 / 2.

This script computes F(L, y) exactly, so the ratio F(2, y) / F(1, y) - the real
price of widening the blocked point into a blocked pair - can be measured
rather than guessed.
"""

import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))

from algorithms.twin_gap import trial_divisors


def odd_primes_upto(limit):
    """Odd primes <= limit, generated by the project's own blocking rule."""
    return [q for q in trial_divisors(limit) if q > 2]


def max_gap(L, y, chunk=1 << 26):
    """Largest gap in S(L, y), computed exactly over one full period."""
    qs = odd_primes_upto(y)
    period = 1
    for q in qs:
        period *= q

    biggest = 0
    first = None
    last = None
    start = 0
    while start < period:
        size = min(chunk, period - start)
        alive = np.ones(size, dtype=bool)
        for q in qs:
            for r in range(L):
                offset = (r - start) % q
                alive[offset::q] = False
        idx = np.flatnonzero(alive)
        if idx.size:
            pos = idx + start
            if first is None:
                first = int(pos[0])
            if last is not None:
                biggest = max(biggest, int(pos[0]) - last)
            if idx.size > 1:
                biggest = max(biggest, int(np.diff(pos).max()))
            last = int(pos[-1])
        start += size

    if first is None:
        return None, period  # blocked everywhere (happens once L >= 3, at q = 3)
    biggest = max(biggest, (period - last) + first)
    return biggest, period


if __name__ == "__main__":
    ys = [int(a) for a in sys.argv[1:]] or [5, 7, 11, 13, 17, 19, 23]
    print(f"{'y':>4} {'F(1,y)':>8} {'F(2,y)':>8} {'ratio':>7} {'2F(2)':>8} "
          f"{'y^2-y-2':>9} {'headroom':>9}")
    for y in ys:
        f1, _ = max_gap(1, y)
        f2, _ = max_gap(2, y)
        limit = y * y - y - 2
        print(f"{y:>4} {f1:>8} {f2:>8} {f2 / f1:>7.2f} {2 * f2:>8} {limit:>9} "
              f"{limit - 2 * f2:>9}")
