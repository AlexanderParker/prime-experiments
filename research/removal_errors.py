"""Exact measurement of what one divisor does to the surviving adjacent pairs.

Section 7 of docs/twin-prime-program.md localises the twin prime conjecture to a
statement about a single divisor at a time. In halved coordinates the algorithm's
unblocked set with divisors up to y is

    S(y) = { h : h != 0 (mod q) for every odd prime q <= y }

and a twin corresponds to an adjacent pair (h, h+1) with both members in S(y).
Let A_y(X) be the number of such pairs in [1, X]. Adding the next divisor q
destroys a pair only when q | h or q | h + 1, which suggests

    A_q(X) = A_prev(X) * (1 - 2/q) + E_q(X)

This script computes A_y(X) exactly for every divisor in turn and prints the
error E_q(X) both absolutely and as a share of the pairs actually removed. The
question the numbers have to answer is whether any single q can take much more
than its 2/q share.
"""

import math
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))

from algorithms.twin_gap import trial_divisors


def odd_primes_upto(limit):
    """Odd primes <= limit, generated by the project's own blocking rule."""
    return [q for q in trial_divisors(limit) if q > 2]


def pair_count(alive):
    """Number of adjacent pairs (h, h+1) with both alive."""
    return int(np.count_nonzero(alive[:-1] & alive[1:]))


def run(X, y=None):
    y = y or math.isqrt(X)
    qs = odd_primes_upto(y)
    # alive[h] for h in 0..X, with h = 0 excluded so indices read directly
    alive = np.ones(X + 2, dtype=bool)
    alive[0] = False

    prev = pair_count(alive)
    print(f"X = {X}, divisors up to y = {y}, starting pairs = {prev}")

    rows = []
    for q in qs:
        before = prev
        alive[q::q] = False
        now = pair_count(alive)
        predicted = before * (1 - 2 / q)
        err = now - predicted
        rows.append(
            {
                "q": q,
                "pairs": now,
                "before": before,
                "err": err,
                # the quantity the induction needs bounded: the error as a
                # fraction of the pairs that were available to remove
                "err_share": err / before,
                "removed_share": (before - now) / before,
            }
        )
        prev = now

    worst = sorted(rows, key=lambda r: -abs(r["err_share"]))[:10]
    print("\nlargest |E_q| relative to the pairs available before that divisor:")
    print(f"{'q':>6} {'pairs after':>12} {'E_q':>10} {'E_q/before':>12} "
          f"{'removed share':>14} {'2/q':>8}")
    for r in worst:
        print(f"{r['q']:>6} {r['pairs']:>12} {r['err']:>10.1f} "
              f"{r['err_share']:>12.5f} {r['removed_share']:>14.5f} "
              f"{2 / r['q']:>8.5f}")

    negative = [r for r in rows if r["err"] < 0]
    product = X
    for q in qs:
        product *= 1 - 2 / q
    print(f"\ndivisors used: {len(rows)}   with E_q < 0: {len(negative)}")
    print(f"max |E_q| = {max(abs(r['err']) for r in rows):.1f}, "
          f"max |E_q|/before = {max(abs(r['err_share']) for r in rows):.5f}")
    print(f"final pairs = {prev}, product model = {product:.1f}, "
          f"ratio = {prev / product:.4f}")
    return prev


if __name__ == "__main__":
    X = int(sys.argv[1]) if len(sys.argv) > 1 else 10**6
    y = int(sys.argv[2]) if len(sys.argv) > 2 else None
    run(X, y)
