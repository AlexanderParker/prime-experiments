"""og_monoid.py -- P8: the dilation twin. Machines with the same dilation structure on other monoids.

(a) S^+ = {n in S : Omega(n) even} (S = the fold's survivors): closed under multiplication; its
    irreducibles are the products of two primes >= 5 (Omega = 2). Its cuts: c_1 = 25 (the least
    irreducible), c_{k+1} = g_k^2 with g_k the least irreducible >= c_k. Step 8 on S^+: a column with both
    members irreducible in S^+ inside every section [g_k^2, g_{k+1}^2). Measured on the first two sections
    and on a prefix of the third.
(b) S_H for H = {+-1} mod 12: S = {n = +-1 (mod 12)}, closed under multiplication, periodic; irreducibles
    = primes = +-1 (mod 12) and products of two primes = +-5 (mod 12). Column = (12j - 1, 12j + 1).
    Step 8 on S_H at its first sections. (The parity mix: irreducibles that are primes and irreducibles
    that are products of two primes, in one periodic dilation machine.)
(c) the monoid generated by the primes = 1 (mod 4): irreducibles never at distance 2 (a congruence), so
    its step 8 (distance 2) fails at every section; its fold is infinite (every prime = 3 (mod 4) is
    removed). Stated, and the first section's irreducibles listed.
Output: results/monoid.json
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from og_common import primes_upto, spf_table

HERE = os.path.dirname(__file__)
RES = os.path.join(HERE, "results")
os.makedirs(RES, exist_ok=True)


def omega(n, spf):
    c = 0
    while n > 1:
        n //= int(spf[n])
        c += 1
    return c


def main():
    N = 4_000_000
    spf = spf_table(N)
    out = {}
    # (a) S^+
    def irr_plus(n):
        return n % 6 in (1, 5) and omega(n, spf) == 2
    g1 = 25
    c2 = g1 * g1
    g2 = next(n for n in range(c2, c2 + 1000) if irr_plus(n))
    c3 = g2 * g2
    g3 = next(n for n in range(c3, c3 + 10000) if irr_plus(n))
    secs = [(c2, c3), (c3, min(g3 * g3, N))]
    a_res = dict(g=[g1, g2, g3], cuts=[c2, c3, g3 * g3], sections=[])
    for lo, hi in secs:
        twins = []
        for j in range(lo // 6 + 1, (hi - 1) // 6 + 1):
            l, r = 6 * j - 1, 6 * j + 1
            if l > lo and r < hi and irr_plus(l) and irr_plus(r):
                twins.append(j)
        a_res["sections"].append(dict(lo=lo, hi=hi, prefix_only=hi < g3 * g3, n_twin_irreducible_cols=len(twins),
                                      first=[(6 * j - 1, 6 * j + 1) for j in twins[:5]]))
    out["S_plus"] = a_res
    print("S^+:", json.dumps(a_res))
    # (b) S_H, H = {+-1} mod 12
    def in_H(n):
        return n % 12 in (1, 11)

    def irr_H(n):
        if not in_H(n) or n == 1:
            return False
        # irreducible iff no proper factorisation a*b with a, b in S_H, 1 < a <= b
        a = 2
        while a * a <= n:
            if n % a == 0 and in_H(a) and in_H(n // a):
                return False
            a += 1
        return True
    g1 = 11
    c2 = 121
    g2 = next(n for n in range(c2, c2 + 1000) if irr_H(n))
    c3 = g2 * g2
    g3 = next(n for n in range(c3, c3 + 10000) if irr_H(n))
    secs = [(c2, c3), (c3, min(g3 * g3, N))]
    b_res = dict(g=[g1, g2, g3], cuts=[c2, c3, g3 * g3], sections=[])
    for lo, hi in secs:
        twins = []
        prime_prime = 0
        mixed = 0
        semi_semi = 0
        for j in range(lo // 12 + 1, (hi - 1) // 12 + 1):
            l, r = 12 * j - 1, 12 * j + 1
            if l > lo and r < hi and irr_H(l) and irr_H(r):
                twins.append(j)
                ol, orr = omega(l, spf), omega(r, spf)
                if ol == 1 and orr == 1:
                    prime_prime += 1
                elif ol == 2 and orr == 2:
                    semi_semi += 1
                else:
                    mixed += 1
        b_res["sections"].append(dict(lo=lo, hi=hi, prefix_only=hi < g3 * g3, n_twin_irreducible_cols=len(twins),
                                      prime_prime=prime_prime, mixed=mixed, semi_semi=semi_semi,
                                      first=[(12 * j - 1, 12 * j + 1) for j in twins[:6]]))
    out["S_H_pm1_mod12"] = b_res
    print("S_H:", json.dumps(b_res))
    # (d) M = the monoid generated by 5 and the primes = 1 (mod 6): a dilation machine on a NON-periodic
    #     base with columns whose members are both in M; its irreducibles are 5 and the primes = 1 (mod 6);
    #     a left member 6j - 1 = 5 (mod 6) is in M iff it has an odd number of factors 5, so it is
    #     irreducible only if it is 5: no twin-irreducible column beyond (5, 7).
    def in_M(n):
        while n % 5 == 0:
            n //= 5
        while n > 1:
            q_ = int(spf[n])
            if q_ % 6 != 1:
                return False
            n //= q_
        return True

    def irr_M(n):
        return n == 5 or (n % 6 == 1 and spf[n] == n and n > 1)
    g1 = 5
    c2 = 25
    g2 = next(n for n in range(c2, c2 + 100) if irr_M(n))
    c3 = g2 * g2
    g3 = next(n for n in range(c3, c3 + 100) if irr_M(n))
    c4 = g3 * g3
    d_res = dict(g=[g1, g2, g3], cuts=[c2, c3, c4], sections=[])
    for lo, hi in [(c2, c3), (c3, c4)]:
        both = 0
        twin_irr = 0
        irr = 0
        ex = []
        for j in range(lo // 6 + 1, (hi - 1) // 6 + 1):
            l, r = 6 * j - 1, 6 * j + 1
            if l <= lo or r >= hi:
                continue
            il, ir = irr_M(l), irr_M(r)
            irr += il + ir
            if in_M(l) and in_M(r):
                both += 1
                if len(ex) < 4:
                    ex.append((l, r))
                if il and ir:
                    twin_irr += 1
        d_res["sections"].append(dict(lo=int(lo), hi=int(hi), irreducibles=int(irr),
                                      cols_both_members_in_M=int(both),
                                      twin_irreducible_cols=int(twin_irr), first_both=ex))
    out["M_5_and_1mod6"] = d_res
    print("M_5_1mod6:", json.dumps(d_res))
    # (c) primes = 1 mod 4
    P1 = [int(p) for p in primes_upto(400) if p % 4 == 1]
    c_res = dict(first_irreducibles=P1[:12], cuts=[5, 25, 29 * 29], distance_2_pairs="none, by the congruence")
    out["P_1mod4"] = c_res
    print("P_1mod4:", json.dumps(c_res))
    with open(os.path.join(RES, "monoid.json"), "w") as f:
        json.dump(out, f, indent=1)


if __name__ == "__main__":
    main()
