"""fm_common.py -- shared constructions for the fold-mechanic lane (research/proof/fold_mechanic.md).

Objects, by construction:
  the fold {2, 3}; survivors S = {6j - 1, 6j + 1} (and 1); class chi(n) = +1 if n = 1 (mod 6), -1 if n = 5 (mod 6);
  column j = (6j - 1, 6j + 1): left member L_j (class -1), right member R_j (class +1);
  gear g (a prime >= 5), class eps_g = chi(g), column k_g (g = 6 k_g + eps_g);
  g strikes column j on the left iff g | 6j - 1 iff j = 6^{-1} (mod g); on the right iff j = -6^{-1} (mod g);
  P_- = class -1 primes, P_+ = class +1 primes; W = twin lowers {t : t, t + 2 prime, t >= 5} (a subset of P_-);
  M_G = the monoid generated by a set G of primes >= 5; its gears are G; its columns are pairs (n, n + 2) in M_G;
  its cuts c_1 = min G, p_k = least element of G >= c_k, c_{k+1} = p_k^2; its finer sections [g^2, g'^2), g < g' consecutive in G.
"""
import numpy as np

N_DEFAULT = 10_000_000


def primes_upto(n):
    s = np.ones(n + 1, dtype=bool)
    s[:2] = False
    for i in range(2, int(n ** 0.5) + 1):
        if s[i]:
            s[i * i::i] = False
    return np.flatnonzero(s)


def spf_table(N):
    """smallest prime factor for 0..N (int32); spf[1] = 1, spf[0] = 0"""
    spf = np.zeros(N + 1, dtype=np.int32)
    spf[1] = 1
    for i in range(2, int(N ** 0.5) + 1):
        if spf[i] == 0:
            spf[i] = i
            blk = spf[i * i::i]
            mask = blk == 0
            blk[mask] = i
            spf[i * i::i] = blk
    rest = np.flatnonzero(spf == 0)
    spf[rest] = rest
    return spf


def chi(n):
    """the class of a survivor: +1 for 1 (mod 6), -1 for 5 (mod 6)"""
    r = n % 6
    if r == 1:
        return 1
    if r == 5:
        return -1
    raise ValueError(n)


def k_of(g):
    """the column holding g: g = 6 k +- 1"""
    return (g + 1) // 6 if g % 6 == 5 else (g - 1) // 6


def inv6(g):
    """6^{-1} mod g: the residue of the columns whose LEFT member g strikes"""
    return pow(6, -1, g)


def column_of(n):
    return (n + 1) // 6 if n % 6 == 5 else (n - 1) // 6


def in_monoid_mask(spf, gen_mask):
    """bool array over 0..N: n is a product of primes in the generator set (gen_mask[p] True for p in G).
    1 is in the monoid; 0 is not. Propagation by smallest prime factor, Omega(n) <= 24 rounds at N = 1e7."""
    N = len(spf) - 1
    n = np.arange(N + 1, dtype=np.int64)
    good = np.zeros(N + 1, dtype=bool)
    good[1] = True
    q = n // np.maximum(spf, 1)  # n / spf(n), = 1 for primes
    q[0] = 0
    prime_ok = gen_mask[spf]
    prime_ok[0] = False
    prime_ok[1] = True
    # good[n] = prime_ok[n] and good[q[n]]; iterate to a fixed point (depth <= 24)
    good = prime_ok & good[q]
    good[1] = True
    for _ in range(30):
        new = prime_ok & good[q]
        new[1] = True
        if np.array_equal(new, good):
            break
        good = new
    return good


def chain_from(G_sorted, c1, N):
    """the cuts of M_G from c_1: list of (c_k, p_k) with p_k the least generator >= c_k, until c_k > N.
    G_sorted: sorted numpy array of generators."""
    out = []
    c = c1
    while c <= N:
        i = int(np.searchsorted(G_sorted, c))
        if i >= len(G_sorted):
            break
        p = int(G_sorted[i])
        out.append((int(c), p))
        c = p * p
    return out


def real_section_columns(lo, hi):
    """columns a+1 .. b-1 with 6a + 1 = lo, 6b + 1 = hi (lo, hi = p^2, p'^2, both = 1 (mod 6))"""
    a = (lo - 1) // 6
    b = (hi - 1) // 6
    return a + 1, b - 1
